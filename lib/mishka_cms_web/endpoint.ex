defmodule MishkaCmsWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :mishka_cms
  use Absinthe.Phoenix.Endpoint

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_mishka_cms_key",
    signing_salt: "7SVW7Y9A",
    same_site: "Lax"
  ]

  # LiveView socket with dynamic origin checking for multi-tenant. The sign-in pages' forms are rate
  # limited by the address `RemoteIp` reads off `:x_headers`, or `:peer_data` names — see
  # `MishkaCmsWeb.RuntimeLive`'s `@client_request`.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [
      connect_info: [:peer_data, :x_headers, session: @session_options],
      check_origin: {MishkaCmsCore.Runtime.OriginValidator, :verify_origin?, []},
      timeout: 60_000
    ],
    longpoll: [
      connect_info: [:peer_data, :x_headers, session: @session_options],
      check_origin: {MishkaCmsCore.Runtime.OriginValidator, :verify_origin?, []}
    ]

  # `:uri` names the host, which is the site the socket is bound to, and `auth_token` carries a bearer
  # token in a header rather than the address; `error_handler` answers a connect refused for its
  # site's state as `/gql` does — see `MishkaCmsWeb.GraphqlSocket`.
  socket "/ws/gql", MishkaCmsWeb.GraphqlSocket,
    websocket: [
      connect_info: [:uri],
      error_handler: {MishkaCmsWeb.GraphqlSocket, :handle_error, []}
    ],
    longpoll: [connect_info: [:uri]],
    auth_token: true

  # WHO IS ASKING, behind the reverse proxies: `conn.remote_ip` becomes the client `x-forwarded-for`
  # names, read right to left past private addresses and the trusted proxies — see
  # `MishkaCmsCore.Accounts.AuthRateLimit.remote_ip_options/0`.
  plug RemoteIp, MishkaCmsCore.Accounts.AuthRateLimit.remote_ip_options()

  # A site's uploaded files are served only while that site is up, and sent `no-cache` so a browser
  # or a CDN asks again before every reuse — a copy kept from while the site was up would outlive it.
  plug MishkaCms.Plugs.UploadsGate, session: @session_options

  plug Plug.Static,
    at: "/",
    from: :mishka_cms,
    gzip: !code_reloading?,
    only: ~w(uploads),
    cache_control_for_etags: "no-cache",
    cache_control_for_vsn_requests: "no-cache"

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :mishka_cms,
    gzip: !code_reloading?,
    only: MishkaCmsWeb.static_paths() -- ~w(uploads)

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug AshPhoenix.Plug.CheckCodegenStatus
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :mishka_cms
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json, Absinthe.Plug.Parser, AshJsonApi.Plug.Parser],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug MishkaCmsWeb.Router
end
